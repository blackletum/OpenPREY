HEADER = ("// Copyright (C) 2026 DarkMatter Productions. GPL-3.0-or-later.\n"
          "// Generated by tools/ui/build_retained_weapon_wheel.py from docs/dev/prey-ui-visual-design.md;\n"
          "// regenerate instead of editing.\n")

# The ring's slots, clockwise from the top, in the weapon bar's order: each
# weapon's def_weapon number less one, its weapon-bar icon and its name on
# the Controls page.
ROSTER = [
    ("wrench", "#str_20222"),
    ("rifle", "#str_20223"),
    ("sw_crawler", "#str_20224"),
    ("soulstripper", "#str_20228"),
    ("autocannon", "#str_20225"),
    ("acidsprayer", "#str_20226"),
    ("rocketlauncher", "#str_20227"),
]
N = len(ROSTER)
SPAN = math.tau / N
C = 280.0                    # the wheel's centre in its 560 dp square

# Section 10.2's HUD palette.
INK = "#A0B2CA"              # hud.ink
INK_LIGHT = "#CAE1FF"        # hud.ink highlight
WELL = "#1C242D"             # hud.well
SELECTOR_RIM = "#748DA8"     # hud.selector rim
SELECTOR_FILL = "#4C5BD3"    # hud.selector fill
AMMO_LINE = "#8CA1E6"        # hud.ammo.line
ALT_LINE = "#596BFF"         # hud.ammo.line, alternate
LOW_LINE = "#731A1A"         # hud.ammo.line, low
EMPTY_RED = 0.75             # the weapon bar's EMPTY_RED
DIM = 0.75                   # the weapon bar's DIM
TEXT = "#FFFFFF"             # hud.text
COUNT = "#B3CCE6"            # the multiplayer counts' blue
DANGER = "#FF1A00"           # hud.danger, low-ammo flicker
TEAM = ["#FF0000", "#3380CC"]  # section 10.6

# The ring, in dp.
INNER, OUTER, OUTER_SELECTED = 100.0, 228.0, 240.0
GAP = 6.0                    # between neighbouring tiles
LEAN = math.radians(6.0)     # the outer edge runs ahead of the inner: the bar's forward shear
CHAMFER = 16.0               # the outer trailing corner, cut as the bar's tile is
ICON_RADIUS = 160.0
ICON_REST = (72.0, 36.0)     # the bar's 50x28 u icon, at the art's own 2:1
ICON_SELECTED = (88.0, 44.0)  # the bar's 60x35 u chosen icon
AMMO_RADIUS = (205.0, 208.0)
ALT_RADIUS = (211.5, 214.5)
INDEX_RADIUS = 116.0
HUB = 86.0

PLACEHOLDER = ui.PLACEHOLDER
BODY = ui.BODY


# --------------------------------------------------------------- helpers

def S(key: str) -> dict:
    return {"state": key}


def op(name: str, *args) -> dict:
    return {"op": name, "args": list(args)}


def choose(condition, yes, no) -> dict:
    return op("select", condition, yes, no)


def at(radius: float, angle: float) -> tuple[float, float]:
    """A point `radius` dp from the centre, `angle` radians clockwise from the top."""
    return (C + radius * math.sin(angle), C - radius * math.cos(angle))


def arc(radius: float, start: float, end: float, steps: int = 20) -> list:
    return [at(radius, start + (end - start) * i / steps) for i in range(steps + 1)]


def lean(radius: float) -> float:
    """How far a tile's edge has leaned at this radius."""
    return LEAN * (radius - INNER) / (OUTER - INNER)


def tile_points(slot: int, outer: float = OUTER, chamfer: bool = True) -> list:
    """A tile's outline: the inner arc, the leading edge out to the outer arc,
    back along it to the chamfered trailing corner, and in again."""
    a = slot * SPAN
    half = SPAN / 2
    d0 = math.asin(GAP / 2 / INNER)
    d1 = math.asin(GAP / 2 / outer)
    l0, r0 = a - half + d0, a + half - d0
    l1, r1 = a - half + d1 + lean(outer), a + half - d1 + lean(outer)
    points = arc(INNER, r0, l0)
    if chamfer:
        cut = CHAMFER / outer
        points += arc(outer, l1, r1 - cut)
        points.append(at(outer - CHAMFER, r1 - (lean(outer) - lean(outer - CHAMFER))))
    else:
        points += arc(outer, l1, r1)
    return points


def dp(points) -> list:
    return [[round(x, 3), round(y, 3)] for x, y in points]


def path(ident: str, points, *, fill=None, stroke=None, blend=None, closed: bool = True) -> dict:
    result = ui.poly(ident, dp(points), fill=fill, stroke=stroke, closed=closed)
    if blend:
        result["blend"] = blend
    return result


def circle(ident: str, radius: float, *, fill=None, stroke=None, cx: float = C, cy: float = C) -> dict:
    return ui.svg(ident, ui.ellipse_d(cx, cy, radius, radius), scale=(1, 1), fill=fill, stroke=stroke)


def art(ident: str, paths: list, **props) -> dict:
    return ui.vector(ident, {**ui.FULL, "display": ui.keyword("block"), "opacity": ui.number(1), **props}, paths)


def full(ident: str, children: list, **props) -> dict:
    return ui.group(ident, {**ui.FULL, "display": ui.keyword("block"), **props}, children)


def masked(ident: str, children: list, paths: list, **props) -> dict:
    node = full(ident, children, **props)
    node["mask"] = {"paths": paths}
    return node


def dp_transform(tx: float = 0, ty: float = 0, sx: float = 1, sy: float = 1, rotation: float = 0) -> dict:
    return {"type": "transform", "unit": "dp", "value": [round(tx, 3), round(ty, 3), sx, sy, rotation]}


def box(cx: float, cy: float, w: float, h: float) -> dict:
    return {"position": ui.keyword("absolute"), "left": ui.length(cx - w / 2), "top": ui.length(cy - h / 2),
            "width": ui.length(w), "height": ui.length(h)}


def text(ident: str, key: str, cx: float, cy: float, w: float, size: float, tint, **props) -> dict:
    """One line of the body face centred on (cx, cy), in dp."""
    return {"id": ident, "type": "text", "properties": {
        "text": ui.text(key), **box(cx, cy, w, size * 1.4),
        "font-family": ui.font(BODY), "font-size": ui.length(size), "line-height": ui.length(size * 1.4),
        "text-align": ui.keyword("center"), "white-space": ui.keyword("nowrap"),
        "color": ui.colour(tint), "display": ui.keyword("block"), **ui.PASSIVE, **props}}


def held(node: str, prop: str, keys: list) -> dict:
    """A track that takes effect from its first key at once: a timeline that
    starts retargets its first key to the property's current value, so the
    authored start is repeated 1 ms later."""
    if len(keys) >= 2 and keys[1][0] > 1:
        keys = [keys[0], (1, keys[0][1])] + list(keys[1:])
    return ui.track(node, prop, keys)


EASE_OUT = [0.16, 1, 0.3, 1]


# -------------------------------------------------------------- document

def document() -> dict:
    doc = ui.Document("openpr06.weapon-wheel")
    for key, kind, initial in [
            ("blend", "number", 0), ("offset", "number", 0), ("fit", "number", 1),
            ("selected", "number", 0), ("previous", "number", -1), ("mp", "boolean", False), ("team", "number", -1),
            ("cursorX", "number", 0), ("cursorY", "number", 0), ("cursorShown", "boolean", False),
            ("ammo", "number", 0), ("alt", "number", 0), ("hasAlt", "boolean", False),
            ("infinite", "boolean", False), ("empty", "boolean", False), ("low", "boolean", False)]:
        doc.state[key] = {"type": kind, "initial": initial}
    doc.state["reduced"] = {"type": "boolean", "initial": False, "cvar": "ui_retainedReducedMotion"}

    def show(node: str, condition) -> None:
        doc.bind(node, "display", choose(condition, "block", "none"))

    team = choose(S("mp"), S("team"), -1)
    teamed = op(">=", team, 0)
    opening, closing, selection = [], [], []
    flashes, names = [], []

    # A soft dark wash under the ring keeps its ink legible over a bright scene;
    # the depth of field the player asks for does the rest.
    wash = circle("wash", 280, fill=ui.radial((C, C), (C + 280, C),
                                              [(0, ui.rgb("#000000", 0.32)), (0.8, ui.rgb("#000000", 0.32)),
                                               (1, ui.rgb("#000000", 0))]))
    wheel = [art("wash", [wash])]

    for i, (icon, name) in enumerate(ROSTER):
        key = f"slot{i}"
        a = i * SPAN
        for suffix, kind, initial in [("owned", "boolean", False), ("empty", "boolean", False),
                                      ("low", "boolean", False), ("altLow", "boolean", False),
                                      ("fill", "number", 0), ("altFill", "number", 0), ("hasAlt", "boolean", False),
                                      ("infinite", "boolean", False)]:
            doc.state[f"{key}.{suffix}"] = {"type": kind, "initial": initial}
        owned, empty = S(f"{key}.owned"), S(f"{key}.empty")
        metered = op("&&", owned, op("!", S(f"{key}.infinite")))   # the wrench has no ammunition to show
        sel = op("==", S("selected"), i)
        chosen = op("&&", owned, sel)
        nodes = []

        # A weapon Tommy does not carry keeps its place as a faint outline.
        outline = art(f"{key}-outline", [path("edge", tile_points(i), stroke=ui.stroke(ui.solid(ui.rgb(INK, 0.18)), 1.0))])
        show(outline["id"], op("!", owned))
        nodes.append(outline)

        rest = art(f"{key}-rest", [
            path("well", tile_points(i), fill=ui.solid(ui.rgb(WELL, 0.5))),
            path("edge", tile_points(i), stroke=ui.stroke(ui.solid(ui.rgb(INK, 0.55)), 1.2, join="round"))])
        show(rest["id"], op("&&", owned, op("!", sel)))
        nodes.append(rest)
        lit = tile_points(i, OUTER_SELECTED)
        for suffix, rim, condition in [("", SELECTOR_RIM, op("!", teamed)),
                                       ("-team0", TEAM[0], op("==", team, 0)),
                                       ("-team1", TEAM[1], op("==", team, 1))]:
            node = art(f"{key}-chosen{suffix}", [
                path("well", lit, fill=ui.solid(ui.rgb(WELL, 0.72))),
                path("selector", lit, fill=ui.solid(ui.rgb(SELECTOR_FILL, 0.15))),
                path("rim", lit, stroke=ui.stroke(ui.solid(ui.rgb(rim, 0.85 if suffix else 0.75)), 2.0, join="round"))])
            show(node["id"], op("&&", chosen, condition))
            nodes.append(node)
        flash = art(f"{key}-flash", [path("rim", lit, stroke=ui.stroke(ui.solid(ui.rgb(INK_LIGHT, 1)), 2.4, join="round"))])
        show(flash["id"], chosen)
        flashes.append(flash)

        # The icon, as the weapon bar draws it: dimmed at rest, full when
        # chosen, its green and blue pulled down when the weapon is empty.
        cx, cy = at(ICON_RADIUS, a + lean(ICON_RADIUS))
        for suffix, (w, h), level, condition in [("rest", ICON_REST, DIM, op("!", sel)),
                                                 ("chosen", ICON_SELECTED, 1.0, sel)]:
            ident = f"{key}-icon-{suffix}"
            picture = ui.picture(ident, f"textures/interface/icons/{icon}",
                                 {**box(cx, cy, w, h), "display": ui.keyword("block"), "opacity": ui.number(1),
                                  "image-color": ui.colour([level, level, level, 1]), **ui.PASSIVE}, fit="contain")
            red = level * (1 - EMPTY_RED)
            doc.bind(ident, "image-color", [level, choose(empty, red, level), choose(empty, red, level), 1])
            show(ident, op("&&", owned, condition))
            nodes.append(picture)

        # The weapon bar's two ammo lines, bent along the tile's outer edge.
        for line, (r0, r1), fill_key, low_key, tint, condition in [
                ("ammo", AMMO_RADIUS, f"{key}.fill", f"{key}.low", ui.rgb(AMMO_LINE, 1), metered),
                ("alt", ALT_RADIUS, f"{key}.altFill", f"{key}.altLow", ui.rgb(ALT_LINE, 0.8),
                 op("&&", metered, S(f"{key}.hasAlt")))]:
            mid = (r0 + r1) / 2
            pad = math.asin((GAP / 2 + 10) / mid)
            lo, hi = a - SPAN / 2 + pad + lean(mid), a + SPAN / 2 - pad + lean(mid) - CHAMFER / mid
            band = arc(r1, lo, hi, 12) + arc(r0, hi, lo, 12)
            sweep = math.degrees(hi - lo)
            track = art(f"{key}-{line}-track", [path("track", band, fill=ui.solid(ui.rgb(INK, 0.16)))])
            fills = []
            for state_name, colour, shown in [("plain", tint, op("!", S(low_key))),
                                              ("low", ui.rgb(LOW_LINE, 1), S(low_key))]:
                fill = art(f"{key}-{line}-{state_name}", [path("fill", band, fill=ui.solid(colour))])
                show(fill["id"], shown)
                fills.append(fill)
            # A band turned back by its empty share and clipped to its own
            # outline: a fill that shortens toward the leading end.
            turn = full(f"{key}-{line}-turn", fills, transform=dp_transform())
            doc.bind(turn["id"], "transform", [0, 0, 1, 1, op("*", op("-", op("clamp", S(fill_key), 0, 1), 1), sweep)])
            clip = masked(f"{key}-{line}-clip", [turn], [path("mask", band, fill=ui.solid([1, 1, 1, 1]))])
            gauge = full(f"{key}-{line}", [track, clip])
            show(gauge["id"], condition)
            nodes.append(gauge)

        # The slot's key, small, on the tile's inner edge.
        ix, iy = at(INDEX_RADIUS, a + lean(INDEX_RADIUS))
        index = text(f"{key}-index", PLACEHOLDER, ix, iy, 24, 11, ui.rgb(TEXT, 0.55))
        doc.bind(index["id"], "text", op("numberText", i + 1))
        doc.bind(index["id"], "color", [1, 1, 1, choose(owned, 0.55, 0.15)])
        nodes.append(index)

        # The weapon Tommy held before: a notch on the hub's edge.
        notch = art(f"{key}-previous", [path("notch", [at(HUB + 4, a), at(HUB + 12, a - 0.045), at(HUB + 12, a + 0.045)],
                                             fill=ui.solid(ui.rgb(COUNT, 0.7)))])
        show(notch["id"], op("&&", owned, op("==", S("previous"), i)))
        nodes.append(notch)

        entry = full(f"{key}-entry", nodes, opacity=ui.number(1), transform=dp_transform())
        wheel.append(entry)
        delay = i * 14
        start = [(0, ui.number(0))] + ([(delay, ui.number(0))] if delay else [])
        opening.append(held(entry["id"], "opacity", start + [(delay + 110, ui.number(1))]))
        scale = [(0, dp_transform(sx=0.92, sy=0.92))] + ([(delay, dp_transform(sx=0.92, sy=0.92))] if delay else [])
        opening.append(held(entry["id"], "transform", scale + [(delay + 110, dp_transform(), EASE_OUT)]))

        names.append(text(f"name{i}", name, C, 268, 150, 17, ui.rgb(TEXT, 0.95)))
        show(f"name{i}", chosen)

    flash_group = full("selection-flash", flashes, opacity=ui.number(0))
    safe = full("selection-flash-safe", [flash_group])
    show(safe["id"], op("!", S("reduced")))
    wheel.append(safe)
    selection.append(held("selection-flash", "opacity", [(0, ui.number(0.9)), (160, ui.number(0))]))

    # The hub: a dark well ringed in ink, the pointer turning to the choice.
    hub_art = art("hub-art", [
        circle("well", HUB, fill=ui.solid(ui.rgb(WELL, 0.68))),
        circle("ring", HUB, stroke=ui.stroke(ui.solid(ui.rgb(INK, 0.5)), 1.2)),
        circle("inner", HUB - 6, stroke=ui.stroke(ui.solid(ui.rgb(INK, 0.2)), 1.0))])
    pointers = []
    for suffix, tint, condition in [("", INK_LIGHT, op("!", teamed)), ("-team0", TEAM[0], op("==", team, 0)),
                                    ("-team1", TEAM[1], op("==", team, 1))]:
        node = art(f"pointer-art{suffix}", [path("arrow", [at(HUB + 14, 0), at(HUB + 2, -0.07), at(HUB + 5, 0), at(HUB + 2, 0.07)],
                                                  fill=ui.solid(ui.rgb(tint)))])
        show(node["id"], condition)
        pointers.append(node)
    pointer = full("pointer", pointers, transform=dp_transform())
    doc.bind("pointer", "transform", [0, 0, 1, 1, op("*", S("selected"), 360.0 / N)])

    # The readout: the weapon's ammunition and, for a weapon with a second
    # kind, that too after a slash, each 9 dp clear of it; the wrench draws
    # an infinity.
    readout_colour = [choose(S("empty"), c1, c0) for c0, c1 in zip(ui.rgb(COUNT), ui.rgb(DANGER))]
    solo = text("hub-ammo", PLACEHOLDER, C, 298, 120, 19, ui.rgb(COUNT))
    doc.bind("hub-ammo", "text", op("numberText", S("ammo")))
    doc.bind("hub-ammo", "color", readout_colour)
    show("hub-ammo", op("&&", op("!", S("infinite")), op("!", S("hasAlt"))))
    first = text("hub-ammo-first", PLACEHOLDER, C - 37, 298, 56, 19, ui.rgb(COUNT), **{"text-align": ui.keyword("right")})
    doc.bind("hub-ammo-first", "text", op("numberText", S("ammo")))
    doc.bind("hub-ammo-first", "color", [choose(S("empty"), c1, c0) for c0, c1 in zip(ui.rgb(COUNT), ui.rgb(DANGER))])
    second = text("hub-ammo-second", PLACEHOLDER, C + 37, 298, 56, 19, ui.rgb(ALT_LINE),
                  **{"text-align": ui.keyword("left")})
    doc.bind("hub-ammo-second", "text", op("numberText", S("alt")))
    slash = art("hub-ammo-slash", [path("slash", [(C + 3, 289), (C - 3, 307)], stroke=ui.stroke(ui.solid(ui.rgb(INK, 0.6)), 1.2),
                                        closed=False)])
    pair = full("hub-ammo-pair", [first, slash, second])
    show("hub-ammo-pair", op("&&", op("!", S("infinite")), S("hasAlt")))
    infinity = ui.svg("infinity", f"M{C} 298C{C - 22} 280 {C - 22} 316 {C} 298C{C + 22} 280 {C + 22} 316 {C} 298Z",
                      scale=(1, 1), stroke=ui.stroke(ui.solid(ui.rgb(COUNT)), 1.6, join="round"))
    infinity_art = art("hub-infinity", [infinity])
    show("hub-infinity", S("infinite"))
    name_wrap = full("hub-name", names, opacity=ui.number(1))
    readout = full("hub-readout", [solo, pair, infinity_art], opacity=ui.number(1))
    hub = full("hub", [hub_art, pointer, name_wrap, readout], transform=dp_transform(), opacity=ui.number(1))
    wheel.append(hub)

    opening += [held("hub", "transform", [(0, dp_transform(sx=0.6, sy=0.6)), (160, dp_transform(), EASE_OUT)]),
                held("hub", "opacity", [(0, ui.number(0)), (90, ui.number(1))]),
                held("hub-name", "opacity", [(0, ui.number(0)), (120, ui.number(0)), (220, ui.number(1))]),
                held("hub-readout", "opacity", [(0, ui.number(0)), (150, ui.number(0)), (250, ui.number(1))])]
    closing += [held("hub", "transform", [(0, dp_transform()), (120, dp_transform(sx=0.9, sy=0.9))])]
    selection += [held("hub-name", "opacity", [(0, ui.number(0.25)), (110, ui.number(1))]),
                  held("hub-readout", "opacity", [(0, ui.number(0.25)), (130, ui.number(1))])]

    # The mouse's selector: a dot the player keeps inside the ring. A stick,
    # a finger or a tracked hand points by direction and leaves it hidden.
    cursor = art("cursor", [circle("halo", 5.5, fill=ui.solid([0, 0, 0, 0.55])),
                            circle("dot", 3.5, fill=ui.solid(ui.rgb(INK_LIGHT)))], transform=dp_transform())
    doc.bind("cursor", "transform", [S("cursorX"), S("cursorY"), 1, 1, 0])
    show("cursor", S("cursorShown"))
    wheel.append(cursor)

    doc.timeline("open", 260, opening)
    doc.timeline("close", 120, closing)
    doc.timeline("selection", 160, selection)
    for event in ("open", "close", "selection"):
        doc.events[event] = [{"op": "playTimeline", "timeline": event}]

    centre = ui.group("wheel-centre", {"position": ui.keyword("absolute"), "left": ui.length(50, "%"),
                                       "top": ui.length(50, "%"), "width": ui.length(560), "height": ui.length(560),
                                       "margin-left": ui.length(-280), "margin-top": ui.length(-280),
                                       "transform": dp_transform()}, wheel)
    doc.bind("wheel-centre", "transform", [S("offset"), 0, S("fit"), S("fit"), 0])
    root = full("wheel-root", [centre], opacity=ui.number(0), **ui.PASSIVE)
    doc.bind("wheel-root", "opacity", op("clamp", S("blend"), 0, 1))
    result = doc.build(root)
    result["extensions"] = {"openpr06": {
        "reference": "prey-ui-visual-design.md 12.1, Weapon wheel",
        "slots": N,
        "input": "Player-owned radial selection (hhPlayer::UpdateWeaponWheel); no pointer hit testing",
        "cursor": "cursorX/cursorY in wheel dp from the centre, bounded by the tiles' outer edge",
        "placement": "ui_weaponWheelOffset percent of the view's width from the centre, default +27; fitted to "
                     "ui_hudScale and ui_hudSafeInset"}}
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report a stale document instead of writing it")
    args = parser.parse_args()
    text_out = HEADER + json.dumps(document(), ensure_ascii=False, separators=(",", ":")) + "\n"
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text_out:
            print(f"{OUT.relative_to(ROOT).as_posix()} is stale: run tools/ui/build_retained_weapon_wheel.py")
            return 1
        print("weapon wheel document is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text_out, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

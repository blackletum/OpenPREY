"""PREY's weapon wheel (docs/dev/prey-ui-visual-design.md section 12.1,
"Weapon wheel"): guis/hud/weapon_wheel.rui.

    python tools/ui/build_retained_weapon_wheel.py            write the document
    python tools/ui/build_retained_weapon_wheel.py --check    exit 1 if it is stale

The wheel is the weapon bar (section 10.1) bent round a ring: seven tiles,
wrench to launcher clockwise from the top, each a dark translucent well with
Tommy's steel-blue ink, the bar's chamfered top-trailing corner (here the
outer, clockwise corner) and its forward lean (the outer edge runs a few
degrees ahead of the inner). The icons are Prey's own weapon-bar line art
(textures/interface/icons/*), tinted as the bar tints them: dimmed at rest,
full when chosen, red when empty. Two slim lines under each icon are the
bar's ammo and alternate-ammo lines. The hub names the chosen weapon with
Prey's own localized names (the Controls page's weapon labels) and reads
out its ammunition.

Everything the wheel shows comes from the player (hhPlayer::DrawWeaponWheel,
src/Prey/game_weaponwheel.cpp); nothing here is pointer-driven. The canvas
is the retained HUD's 720 dp height; the wheel is a 560 dp square about the
view's centre, moved by ui_weaponWheelOffset and fitted to the HUD scale
and safe inset by the player.
"""
